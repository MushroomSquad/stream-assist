import assert from 'node:assert/strict';
import { createHistory } from './mixerHistory.ts';
const h = createHistory(0);
assert.equal(h.canUndo, false);
assert.equal(h.undo(), 0);
h.push(1); h.push(2); h.push(3);
assert.equal(h.undo(), 2); assert.equal(h.undo(), 1);
assert.equal(h.redo(), 2); h.push(4);
assert.equal(h.canRedo, false); assert.equal(h.redo(), 4);
assert.equal(h.undo(), 2);
const bounded = createHistory(0);
for (let i = 1; i <= 150; i++) bounded.push(i);
for (let i = 0; i < 200; i++) bounded.undo();
assert.equal(bounded.redo(), 52);
const object = createHistory({ weights: [50, 50] });
const next = { weights: [30, 70] }; object.push(next); next.weights[0] = 99;
assert.deepEqual(object.undo(), { weights: [50, 50] });
assert.deepEqual(object.redo(), { weights: [30, 70] });
console.log('mixerHistory: all checks passed');
